def _both(names, canon=None):
    """sqlite3 takes -opt and --opt alike (VERIFIED for -readonly)."""
    out = {}
    for n in names:
        c = (canon or {}).get(n, n.replace("-", "_"))
        out["-" + n] = c
        out["--" + n] = c
    return out


