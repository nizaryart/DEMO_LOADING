"""Generate src/demo_cli/engine/ps_tables_data.py from a PowerShell dump (C3, ruling PS2).

The binder's tables are not written by hand: `dump_bindings.ps1` asks the
installed PowerShell for every cmdlet of Microsoft.PowerShell.Management /
Utility / Core (parameter sets, positions, pipeline binding, switches,
parameter aliases, -WhatIf support) and for every alias, and writes
ps51_bindings.json beside itself. This script turns that dump into a compact
Python module, so the engine imports data, not a file it must locate.

    powershell -NoProfile -File tools\\c3\\dump_bindings.ps1
    python tools/c3/gen_ps_tables.py tools/c3/ps51_bindings.json

A new PowerShell version is a regeneration, not a code change.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "demo_cli", "engine", "ps_tables_data.py")
NAMED = -2147483648          # [int]::MinValue: a parameter with no position


def main(path: str) -> int:
    with open(path, encoding="utf-8-sig") as f:      # Set-Content -Encoding UTF8 writes a BOM
        d = json.load(f)
    cmdlets = {}
    for name, c in sorted(d["cmdlets"].items()):
        sets = []
        for s in c["sets"]:
            params = []
            for p in s["parameters"]:
                params.append((p["name"], -1 if p["position"] == NAMED else p["position"],
                               bool(p["mandatory"]), bool(p["byvalue"]), bool(p["byprop"]),
                               bool(p["switch"]), tuple(p.get("aliases") or ())))
            sets.append((s["name"], bool(s["default"]), tuple(params)))
        cmdlets[name] = (bool(c.get("whatif")), tuple(sets))
    aliases = dict(sorted(d["aliases"].items(), key=lambda kv: kv[0].lower()))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write('"""GENERATED by tools/c3/gen_ps_tables.py from PowerShell %s - do not edit.\n\n'
                % d["version"])
        f.write("CMDLETS: name -> (supports -WhatIf, ((set, is_default, ((param, position or -1,\n"
                "mandatory, ValueFromPipeline, ValueFromPipelineByPropertyName, switch,\n"
                "aliases), ...)), ...)). ALIASES: alias -> cmdlet. COMMON: the common\n"
                "parameters every cmdlet accepts.\n\"\"\"\n")
        f.write("VERSION = %r\n" % d["version"])
        f.write("COMMON = %r\n" % (tuple(d["common"]),))
        f.write("ALIASES = {\n")
        for k, v in aliases.items():
            f.write("    %r: %r,\n" % (k, v))
        f.write("}\nCMDLETS = {\n")
        for k, v in cmdlets.items():
            f.write("    %r: %r,\n" % (k, v))
        f.write("}\n")
    print(f"wrote {os.path.normpath(OUT)}: {len(cmdlets)} cmdlets, {len(aliases)} aliases")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "ps51_bindings.json")))
